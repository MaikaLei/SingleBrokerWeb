    private void carregarTabela() {

        controller.ImovelController dao = new controller.ImovelController();

        DefaultTableModel modelo
                = (DefaultTableModel) tblListaImoveis.getModel();

        modelo.setRowCount(0);

        List<ImovelModel> lista = dao.listar();

        for (ImovelModel imovel : lista) {

            modelo.addRow(new Object[]{
                imovel.getId(),
                imovel.getStatusImovel(),
                imovel.getTransacao(),
                imovel.getTipoImovel(),
                imovel.getValor()

            });
        }
    }

    public void atualizarTabela() {
        String cidade = cbxCidade.getSelectedItem() == null ? "Cidade" : cbxCidade.getSelectedItem().toString();
        String bairro = cbxBairroBusca.getSelectedItem() == null ? "Bairro" : cbxBairroBusca.getSelectedItem().toString();
        List<ImovelModel> imoveis = new controller.ImovelController().listar();
        atualizarOpcoesFiltros(imoveis, cidade, bairro);
        try { buscarImoveis(); } catch (RuntimeException e) { carregarTabela(); }
    }

    private void atualizarOpcoesFiltros(List<ImovelModel> imoveis, String cidadeAtual, String bairroAtual) {
        cbxCidade.removeAllItems();
        cbxCidade.addItem("Cidade");
        imoveis.stream().map(ImovelModel::getCidade).filter(java.util.Objects::nonNull).distinct().sorted().forEach(cbxCidade::addItem);
        cbxBairroBusca.removeAllItems();
        cbxBairroBusca.addItem("Bairro");
        imoveis.stream().map(ImovelModel::getBairro).filter(java.util.Objects::nonNull).map(String::trim)
                .filter(s -> !s.isEmpty()).distinct().sorted().forEach(cbxBairroBusca::addItem);
        cbxCidade.setSelectedItem(cidadeAtual);
        cbxBairroBusca.setSelectedItem(bairroAtual);
    }

    private void buscarImoveis() {

        controller.ImovelController dao = new controller.ImovelController();

        DefaultTableModel modelo
                = (DefaultTableModel) tblListaImoveis.getModel();

        modelo.setRowCount(0);

        List<ImovelModel> lista = dao.buscar(
                txtCodigoBusca.getText().trim(),
                cbxStatus.getSelectedItem().toString(),
                cbxTransacao.getSelectedItem().toString(),
                cbxTipo.getSelectedItem().toString(),
                cbxCidade.getSelectedItem().toString(),
                cbxBairroBusca.getSelectedItem().toString(),
                txtValorMinimo.getText(),
                txtValorMaximo.getText());

        for (ImovelModel imovel : lista) {

            modelo.addRow(new Object[]{
                imovel.getId(),
                imovel.getStatusImovel(),
                imovel.getTransacao(),
                imovel.getTipoImovel(),
                imovel.getValor()
            });
        }
    }

